#!/usr/bin/env python3
"""Regenerate the parameter table in docs/parameters.md from the code.

    python scripts/gen_parameter_table.py            # rewrite the table
    python scripts/gen_parameter_table.py --check    # fail if it is stale (CI)

The table sits between the AUTOGEN markers. Ranges and units come from
`dcrest.BOUNDS` / `dcrest.params.UNITS`, so the document cannot drift from the
implementation; the prose descriptions live in this file.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

import dcrest

BEGIN = "<!-- AUTOGEN:parameters BEGIN -->"
END = "<!-- AUTOGEN:parameters END -->"

WHAT = {
    "tsnow": "air temperature separating snow from rain",
    "ddf": "degree-day melt factor",
    "ft": "interception capacity as a fraction of `wm`",
    "wm": "mean soil-water capacity of the unit",
    "b": "shape of the capacity distribution (VIC curve)",
    "im": "impervious fraction",
    "ke": "multiplier on potential ET",
    "fc": "saturated hydraulic conductivity; caps interflow",
    "ksoil": "soil to aquifer drainage rate",
    "hmaxaq": "aquifer capacity (fill and spill)",
    "gwc": "baseflow coefficient",
    "gwe": "baseflow exponent",
    "qc": "overland linear-reservoir release rate",
    "lf": "fraction of routed flow lost at the outlet",
    "nshape": "Gamma unit-hydrograph shape",
    "kmult": "multiplier on the geomorphic UH scale",
    "ptens": "fraction of soil storage that evaporates but cannot drain",
    "plp": "soil-moisture threshold below which ET is limited",
}


def fmt(x: float) -> str:
    return f"{x:g}"


def table(names) -> str:
    u, d = dcrest.params.UNITS, dcrest.DEFAULTS
    b = dcrest.BOUNDS_TENSION
    rows = ["| name | units | range | default | what it does |",
            "|---|---|---|---|---|"]
    for k in names:
        lo, hi = b[k]
        units = u[k].replace("-", "&mdash;") if u[k] == "-" else u[k]
        rows.append(f"| `{k}` | {units} | {fmt(lo)} … {fmt(hi)} | {fmt(d[k])} "
                    f"| {WHAT[k]} |")
    return "\n".join(rows)


def render() -> str:
    base = list(dcrest.BOUNDS)
    ext = [k for k in dcrest.BOUNDS_TENSION if k not in dcrest.BOUNDS]
    return (f"{BEGIN}\n"
            "*Generated by `scripts/gen_parameter_table.py` — edit that file, "
            "not this table.*\n\n"
            "### The 16 parameters\n\n" + table(base) + "\n\n"
            "### Optional tension-store extension\n\n" + table(ext) + "\n"
            f"{END}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "docs", "parameters.md")
    doc = open(path, encoding="utf-8").read()
    if BEGIN not in doc or END not in doc:
        print(f"markers not found in {path}")
        return 2
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), render(), doc,
                 flags=re.S)
    if args.check:
        if new != doc:
            print("docs/parameters.md is stale; run scripts/gen_parameter_table.py")
            return 1
        print("docs/parameters.md is up to date")
        return 0
    open(path, "w", encoding="utf-8").write(new)
    print(f"wrote the parameter table into {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
